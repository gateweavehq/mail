import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { generate } from "../scripts/generate.mjs";

const read = (path: string) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");

/** A document with what the API's has: a path, a query, a body, open answers, enums and nulls. */
const small = {
	openapi: "3.1.0",
	paths: {
		"/boxes/{box}/notes": {
			get: {
				operationId: "list_notes",
				summary: "List notes",
				description: "Lists a box's notes.",
				"x-mcp-tool": "list_notes",
				parameters: [
					{
						name: "box",
						in: "path",
						required: true,
						description: "The box.",
						schema: { type: "string" },
					},
					{
						name: "words",
						in: "query",
						required: false,
						schema: { type: "string", maxLength: 20 },
					},
					{ name: "limit", in: "query", required: true, schema: { type: "integer", minimum: 1 } },
					{ name: "all", in: "query", required: false, schema: { type: "boolean" } },
				],
				responses: {
					"200": {
						content: {
							"application/json": {
								schema: {
									type: "object",
									properties: {
										notes: {
											type: "array",
											items: {
												type: "object",
												properties: {
													id: { type: "string" },
													color: { type: "string", enum: ["red", "blue"] },
													cut: { type: ["string", "null"], description: "Where it was */ cut." },
												},
												required: ["id", "color"],
												additionalProperties: {},
											},
										},
										next: {
											anyOf: [{ type: "array", items: { type: "number" } }, { type: "null" }],
										},
									},
									required: ["notes"],
									additionalProperties: {},
								},
							},
						},
					},
					"404": { $ref: "#/components/responses/Failed404" },
				},
			},
			post: {
				operationId: "add_note",
				summary: "Add note",
				parameters: [{ name: "box", in: "path", required: true, schema: { type: "string" } }],
				requestBody: {
					required: true,
					content: {
						"application/json": {
							schema: {
								type: "object",
								properties: {
									text: { type: "string", description: "What it says." },
									tags: { type: "array", items: { anyOf: [{ type: "string" }, { type: "null" }] } },
								},
								required: ["text"],
							},
						},
					},
				},
				responses: {
					"200": {
						content: {
							"application/json": {
								schema: {
									type: "object",
									properties: { id: { type: "string" } },
									required: ["id"],
								},
							},
						},
					},
				},
			},
		},
		"/ping": {
			post: {
				operationId: "ping",
				requestBody: {
					content: {
						"application/json": { schema: { type: "object", properties: {}, required: [] } },
					},
				},
				responses: {
					"200": {
						content: { "application/json": { schema: { type: "object", properties: {} } } },
					},
				},
			},
		},
	},
};

describe("generate", () => {
	const made = generate(small);

	it("says it is generated, and not to be edited", () => {
		expect(made.split("\n")[0]).toMatch(
			/^\/\/ Generated by scripts\/generate\.mjs from openapi\.json/,
		);
		expect(made).toContain("Don't\n// edit it by hand");
		expect(made).toContain("pnpm --filter @gateweave/mail generate");
	});

	it("takes a route's path, query and body inputs in one, saying which it may leave out", () => {
		expect(made).toContain(
			[
				"export interface ListNotesInput {",
				"\t/** The box. */",
				"\tbox: string;",
				"\twords?: string | undefined;",
				"\tlimit: number;",
				"\tall?: boolean | undefined;",
				"}",
			].join("\n"),
		);
		expect(made).toContain(
			[
				"export interface AddNoteInput {",
				"\tbox: string;",
				"\t/** What it says. */",
				"\ttext: string;",
				"\ttags?: (string | null)[] | undefined;",
				"}",
			].join("\n"),
		);
		expect(made).toContain("export type PingInput = Record<string, never>;");
	});

	it("gives a route's answer, open where the schema is, with its words", () => {
		expect(made).toContain(
			[
				"export interface ListNotesOutput {",
				"\tnotes: {",
				"\t\tid: string;",
				'\t\tcolor: "red" | "blue";',
				"\t\t/** Where it was *\\/ cut. */",
				"\t\tcut?: string | null;",
				"\t\t[key: string]: unknown;",
				"\t}[];",
				"\tnext?: number[] | null;",
				"\t[key: string]: unknown;",
				"}",
			].join("\n"),
		);
		// Closed, as the schema says nothing of more properties.
		expect(made).toContain("export interface AddNoteOutput {\n\tid: string;\n}");
	});

	it("lists each route: its method, path, and where its inputs go", () => {
		expect(made).toContain(
			[
				"\tlist_notes: {",
				'\t\tmethod: "GET",',
				'\t\tpath: "/boxes/{box}/notes",',
				'\t\tpathParams: ["box"],',
				'\t\tqueryParams: ["words", "limit", "all"],',
				"\t\tbody: false,",
				"\t},",
			].join("\n"),
		);
		expect(made).toContain(
			[
				"\tadd_note: {",
				'\t\tmethod: "POST",',
				'\t\tpath: "/boxes/{box}/notes",',
				'\t\tpathParams: ["box"],',
				"\t\tqueryParams: [],",
				"\t\tbody: true,",
				"\t},",
			].join("\n"),
		);
		expect(made).toContain("\tlist_notes: { input: ListNotesInput; output: ListNotesOutput };");
		expect(made).toContain("} as const satisfies Record<OperationId, Route>;");
	});

	it("names a method for each route in camelCase, its input optional when it needs none", () => {
		expect(made).toContain(
			"\tlistNotes(input: ListNotesInput, options?: CallOptions): Promise<ListNotesOutput>;",
		);
		expect(made).toContain(
			"\tping(input?: PingInput, options?: CallOptions): Promise<PingOutput>;",
		);
		expect(made).toContain(
			"\t * List notes.\n\t *\n\t * Lists a box's notes.\n\t *\n\t * `GET /boxes/{box}/notes`, as the MCP tool `list_notes`.",
		);
	});

	it("stops at what it can't turn into TypeScript, rather than guess", () => {
		const output = (schema: Record<string, unknown>) => ({
			paths: {
				"/x": {
					get: {
						operationId: "x",
						responses: { "200": { content: { "application/json": { schema } } } },
					},
				},
			},
		});
		expect(() => generate(output({ $ref: "#/components/schemas/X" }))).toThrow(/\$ref/);
		expect(() => generate(output({ oneOf: [{ type: "string" }] }))).toThrow(/oneOf/);
		expect(() =>
			generate(output({ type: "object", additionalProperties: { type: "string" } })),
		).toThrow(/more properties/);
		// The API reads one value for each name in a query string, so no list goes there.
		const listInQuery = {
			paths: {
				"/x": {
					get: {
						operationId: "x",
						parameters: [
							{ name: "ids", in: "query", schema: { type: "array", items: { type: "string" } } },
						],
						responses: {
							"200": { content: { "application/json": { schema: { type: "object" } } } },
						},
					},
				},
			},
		};
		expect(() => generate(listInQuery)).toThrow(/ids in its query/);
	});

	it("made src/api.gen.ts from openapi.json as it is now", () => {
		const document = JSON.parse(read("openapi.json"));
		expect(
			read("src/api.gen.ts") === generate(document),
			"src/api.gen.ts isn't what openapi.json makes: run `pnpm --filter @gateweave/mail generate`.",
		).toBe(true);
	});
});
